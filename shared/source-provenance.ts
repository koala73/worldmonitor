export function getSourcePropagandaRisk(sourceName: string): SourceRiskProfile {
  return SOURCE_PROPAGANDA_RISK[sourceName] ?? UNREVIEWED_SOURCE_RISK;
}

export function hasReviewedPropagandaRisk(sourceName: string): boolean {
  return Object.prototype.hasOwnProperty.call(SOURCE_PROPAGANDA_RISK, sourceName);
}

/** True when propaganda risk is either reviewed or explicitly declared unknown. */
export function hasDeclaredPropagandaRisk(sourceName: string): boolean {
  return hasReviewedPropagandaRisk(sourceName)
    || Object.prototype.hasOwnProperty.call(CONFIGURED_SOURCE_PROVENANCE_DECLARATIONS, sourceName);
}

export function isStateAffiliatedSource(sourceName: string): boolean {
  const profile = SOURCE_PROPAGANDA_RISK[sourceName];
  return !!profile?.stateAffiliated;
}

/**
 * Tooltip for the Tier 1/2 credibility badge.
 * Never presents unreviewed / non-wire / non-gov sources as "Verified News Outlet".
 */
export function getSourceTierBadgeTitle(sourceType: SourceType): string {
  if (sourceType === 'wire') return 'Wire Service - Highest reliability';
  if (sourceType === 'gov') return 'Official Government Source';
  if (sourceType === 'unknown') return 'Source type not yet reviewed';
  if (sourceType === 'intel') return 'Specialist / intel outlet';
  if (sourceType === 'mainstream') return 'Major news outlet';
  if (sourceType === 'market') return 'Market / financial outlet';
  if (sourceType === 'tech') return 'Technology outlet';
  return 'News source';
}

/**
 * Propaganda-risk badge presentation. `null` only for explicit reviewed `low`
 * (independent journalism). Unknown always surfaces so silence never implies independence.
 */
export function describePropagandaBadge(profile: SourceRiskProfile, sourceType: SourceType = 'unknown'): {
  risk: PropagandaRisk;
  label: string;
  shortLabel: string;
  title: string;
} | null {
  if (profile.risk === 'unknown') {
    return {
      risk: 'unknown',
      label: '? Unreviewed',
      shortLabel: '?',
      title: profile.note || UNREVIEWED_SOURCE_RISK.note || 'Provenance not yet reviewed',
    };
  }
  const title = composeProvenanceSummary(profile, sourceType);
  const withState = (label: string) => (profile.stateAffiliated ? `${label}: ${profile.stateAffiliated}` : label);
  if (sourceType === 'gov') {
    return {
      risk: profile.risk,
      label: withState('Official Government Source'),
      shortLabel: 'Gov',
      title,
    };
  }
  if (profile.risk === 'low') return null;
  if (profile.risk === 'high') {
    return { risk: 'high', label: withState('⚠ State Media'), shortLabel: '⚠', title };
  }
  return { risk: 'medium', label: withState('! Caution'), shortLabel: '!', title };
}

export interface SourceProvenanceState {
  risk: PropagandaRisk;
  type: SourceType;
  riskDeclared: boolean;
  typeDeclared: boolean;
  riskReviewed: boolean;
  typeReviewed: boolean;
  stateAffiliated?: string;
  /** Always present. Empty means no perspective label recorded, never "neutral". */
  knownBiases: readonly string[];
  note?: string;
  /** Every curated fact in fixed clause order; the one tooltip and agent text. */
  summary: string;
}

export interface ProvenanceFact {
  kind: 'state' | 'perspective';
  label: string;
}

export const PERSPECTIVE_LABEL_CAVEAT = 'Perspective labels are recorded for few sources; a source without one has not been assessed, not judged neutral.';

/**
 * Chips shown beside the risk badge: every perspective label, plus the state
 * affiliation when no risk badge carries it (a state-affiliated source rated low).
 * Never filtered by tier.
 */
export function getProvenanceFacts(profile: SourceRiskProfile, sourceType: SourceType): ProvenanceFact[] {
  const stateOnBadge = describePropagandaBadge(profile, sourceType) !== null;
  return [
    ...(profile.stateAffiliated && !stateOnBadge
      ? [{ kind: 'state' as const, label: `State-affiliated: ${profile.stateAffiliated}` }]
      : []),
    ...(profile.knownBiases ?? []).map((label) => ({ kind: 'perspective' as const, label })),
  ];
}

function describeRiskClause(profile: SourceRiskProfile, type: SourceType): string {
  if (profile.risk === 'unknown') return `${UNREVIEWED_SOURCE_RISK.note}.`;
  if (type === 'gov') {
    return profile.stateAffiliated ? `Official government source: ${profile.stateAffiliated}.` : 'Official government source.';
  }
  const state = profile.stateAffiliated ? ` State-affiliated: ${profile.stateAffiliated}.` : '';
  if (profile.risk === 'high') return `State media.${state}`;
  if (profile.risk === 'medium') return `Caution.${state}`;
  return `Reviewed.${state}`;
}

/** One composition for every tooltip and agent summary, so no surface can drop a fact. */
export function composeProvenanceSummary(profile: SourceRiskProfile, type: SourceType): string {
  const knownBiases = profile.knownBiases ?? [];
  const note = profile.note === UNREVIEWED_SOURCE_RISK.note ? undefined : profile.note;
  return [
    describeRiskClause(profile, type),
    knownBiases.length > 0 ? `Perspective: ${knownBiases.join(', ')}.` : 'Perspective: none recorded.',
    ...(note ? [/[.!?]$/.test(note) ? note : `${note}.`] : []),
  ].join(' ');
}

/** Complete, fail-closed provenance state for UI and agent consumers. */
export function getSourceProvenanceState(sourceName: string): SourceProvenanceState {
  const profile = getSourcePropagandaRisk(sourceName);
  const type = getSourceType(sourceName);
  return {
    risk: profile.risk,
    type,
    riskDeclared: hasDeclaredPropagandaRisk(sourceName),
    typeDeclared: hasDeclaredSourceType(sourceName),
    riskReviewed: hasReviewedPropagandaRisk(sourceName),
    typeReviewed: hasReviewedSourceType(sourceName),
    ...(profile.stateAffiliated ? { stateAffiliated: profile.stateAffiliated } : {}),
    knownBiases: profile.knownBiases ?? [],
    ...(profile.note ? { note: profile.note } : {}),
    summary: composeProvenanceSummary(profile, type),
  };
}

export interface ProvenanceCoverage {
  sources: number;
  riskReviewed: number;
  stateAffiliated: number;
  perspectiveLabelled: number;
  caveat: string;
}

let provenanceCoverage: ProvenanceCoverage | null = null;

/** Registry-wide counts, so agents can tell an unlabelled source from an unassessed one. */
export function getProvenanceCoverage(): ProvenanceCoverage {
  if (provenanceCoverage) return provenanceCoverage;
  const names = new Set([
    ...Object.keys(SOURCE_PROPAGANDA_RISK),
    ...Object.keys(SOURCE_TYPES),
    ...Object.keys(CONFIGURED_SOURCE_PROVENANCE_DECLARATIONS),
  ]);
  let riskReviewed = 0;
  let stateAffiliated = 0;
  let perspectiveLabelled = 0;
  for (const name of names) {
    if (!hasReviewedPropagandaRisk(name)) continue;
    riskReviewed += 1;
    const profile = SOURCE_PROPAGANDA_RISK[name]!;
    if (profile.stateAffiliated) stateAffiliated += 1;
    if (profile.knownBiases?.length) perspectiveLabelled += 1;
  }
  provenanceCoverage = {
    sources: names.size,
    riskReviewed,
    stateAffiliated,
    perspectiveLabelled,
    caveat: `Perspective labels are recorded for ${perspectiveLabelled} of ${names.size} sources; a source without one has not been assessed, not judged neutral.`,
  };
  return provenanceCoverage;
}
