export const THEME_IDS = Object.keys(THEMES);

export function getTheme(id) {
  return THEMES[id] || THEMES.neon;
}

export function nextThemeId(id, step = 1) {
  const i = THEME_IDS.indexOf(id);
  const n = THEME_IDS.length;
  return THEME_IDS[(((i < 0 ? 0 : i) + step) % n + n) % n];
}

// Colour for a signed change (markets), a severity word, or a threat level.
export function changeColor(t, value) {
  if (value > 0) return t.good;
  if (value < 0) return t.bad;
  return t.dim;
}

export function severityColor(t, level) {
  const l = String(level || '').toLowerCase();
  if (/critical|extreme|severe|high|crit|do-not-travel|unhealthy|major/.test(l)) return t.bad;
  if (/elevated|medium|moderate|warn|reconsider|degraded|partial|minor/.test(l)) return t.warn;
  if (/low|normal|ok|healthy|operational|caution/.test(l)) return t.good;
  return t.info;
}
