#!/usr/bin/env node
// Embeds the MCP discovery documents in the Edge function bundle. The handler
// used to fetch them from its own public URL on each cold instance; when that
// fetch failed, discovery reads got a 302 instead of the document (production
// smoke runs on 2026-09-04, 2026-11-04 and 2026-11-19).
//
// The server card is embedded without its `tools` list (84 KB of the 99 KB
// file). The handler rebuilds that list from the tool registry already in the
// bundle (api/mcp/server-card-tools.ts); the full card would push api/mcp.ts
// past its compressed budget in tests/edge-function-size.test.mjs.
//
//   node scripts/generate-mcp-discovery-documents.mjs          # rewrite
//   node scripts/generate-mcp-discovery-documents.mjs --check  # exit 1 if stale

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT_PATH = 'api/mcp/discovery-documents.generated.ts';
export const SERVER_CARD_PATH = 'public/.well-known/mcp/server-card.json';
export const GUIDE_PATH = 'public/mcp-server.md';
export const SETUP_PATH = 'public/mcp-setup.html';

/** The card with an empty `tools` list, compact. The key keeps its position. */
export function serverCardWithoutTools(cardSource) {
  const card = JSON.parse(cardSource);
  if (!Array.isArray(card.tools)) throw new Error(`${SERVER_CARD_PATH} must carry a tools array`);
  return JSON.stringify({ ...card, tools: [] });
}

export function renderMcpDiscoveryDocuments(read = (path) => readFileSync(resolve(ROOT, path), 'utf8')) {
  const constants = [
    ['MCP_SERVER_CARD_WITHOUT_TOOLS_JSON', `${SERVER_CARD_PATH} with "tools": []`, serverCardWithoutTools(read(SERVER_CARD_PATH))],
    ['MCP_GUIDE_MARKDOWN', GUIDE_PATH, read(GUIDE_PATH)],
    ['MCP_SETUP_HTML', SETUP_PATH, read(SETUP_PATH)],
  ];
  const lines = [
    '// Generated by scripts/generate-mcp-discovery-documents.mjs from the files under public/. Do not edit.',
  ];
  for (const [name, origin, value] of constants) {
    lines.push('', `// ${origin}`, `export const ${name} = ${JSON.stringify(value)};`);
  }
  return `${lines.join('\n')}\n`;
}

export function generateMcpDiscoveryDocuments({ check = false } = {}) {
  const outputPath = resolve(ROOT, OUTPUT_PATH);
  const expected = renderMcpDiscoveryDocuments();
  let actual = null;
  try {
    actual = readFileSync(outputPath, 'utf8');
  } catch { /* missing output is stale */ }
  if (actual === expected) return [];
  if (!check) writeFileSync(outputPath, expected);
  return [relative(ROOT, outputPath)];
}

const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isCli) {
  const check = process.argv.includes('--check');
  const stale = generateMcpDiscoveryDocuments({ check });
  if (check && stale.length > 0) {
    console.error(`Stale MCP discovery documents: ${stale.join(', ')}\nRun: node scripts/generate-mcp-discovery-documents.mjs`);
    process.exit(1);
  }
  console.log(check ? 'MCP discovery documents current' : `wrote ${OUTPUT_PATH}`);
}
