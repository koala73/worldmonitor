#!/usr/bin/env node
// Generates the land-and-coast acquisition-coverage grid that decides whether an
// optical or radar mission acquires over a point at all (the open missions
// image land and coasts, not open ocean).
//
// Source: public/data/countries-50m.json, the Natural Earth 1:50m admin-0
// TopoJSON the map already ships. A 0.25-degree cell is land when its centre
// lies inside a country polygon or any polygon vertex falls in it (so small
// islands survive), and the grid is then dilated by one cell so coastal
// waters within roughly 28 km of land count as coast.
//
// Each row is stored as alternating water/land run lengths in base 36, which
// keeps the module small enough for a browser worker, an edge handler and a
// Node seeder. It is an inline ES module, not JSON, because JSON imports break
// on the edge path (tests/no-json-import-attributes-on-edge-path.test.mjs).
//
// Usage: node scripts/generate-orbital-land-coast-mask.mjs [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainModule } from './lib/main-module.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_PATH = 'public/data/countries-50m.json';
export const MASK_PATHS = ['shared/orbital/land-coast-mask.data.js', 'scripts/shared/orbital/land-coast-mask.data.js'];
export const CELL_DEG = 0.25;
const DILATE_CELLS = 1;

function decodeArcs(topology) {
  const [sx, sy] = topology.transform.scale;
  const [tx, ty] = topology.transform.translate;
  return topology.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

function ringPoints(ring, arcs) {
  return ring.flatMap((index, k) => {
    const points = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
    return k === 0 ? points : points.slice(1);
  });
}

export function buildMask(topology) {
  const arcs = decodeArcs(topology);
  const width = Math.round(360 / CELL_DEG);
  const height = Math.round(180 / CELL_DEG);
  const land = new Uint8Array(width * height);
  const mark = (row, col) => {
    if (row >= 0 && row < height) land[row * width + (((col % width) + width) % width)] = 1;
  };
  for (const geometry of topology.objects.countries.geometries) {
    const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.type === 'MultiPolygon' ? geometry.arcs : [];
    for (const polygon of polygons) {
      const rings = polygon.map((ring) => ringPoints(ring, arcs));
      for (const ring of rings) {
        for (const [lon, lat] of ring) mark(Math.floor((90 - lat) / CELL_DEG), Math.floor((lon + 180) / CELL_DEG));
      }
      for (let row = 0; row < height; row++) {
        const lat = 90 - (row + 0.5) * CELL_DEG;
        const crossings = [];
        for (const ring of rings) {
          for (let i = 0; i < ring.length - 1; i++) {
            const [x1, y1] = ring[i];
            const [x2, y2] = ring[i + 1];
            if ((y1 > lat) !== (y2 > lat)) crossings.push(x1 + ((lat - y1) * (x2 - x1)) / (y2 - y1));
          }
        }
        crossings.sort((a, b) => a - b);
        for (let i = 0; i + 1 < crossings.length; i += 2) {
          for (let col = Math.ceil((crossings[i] + 180) / CELL_DEG - 0.5); (col + 0.5) * CELL_DEG - 180 <= crossings[i + 1]; col++) {
            mark(row, col);
          }
        }
      }
    }
  }
  const coast = new Uint8Array(width * height);
  for (let row = 0; row < height; row++) {
    for (let col = 0; col < width; col++) {
      if (!land[row * width + col]) continue;
      for (let dr = -DILATE_CELLS; dr <= DILATE_CELLS; dr++) {
        const r = row + dr;
        if (r < 0 || r >= height) continue;
        for (let dc = -DILATE_CELLS; dc <= DILATE_CELLS; dc++) coast[r * width + (((col + dc) % width) + width) % width] = 1;
      }
    }
  }
  const rows = [];
  for (let row = 0; row < height; row++) {
    const runs = [];
    let value = 0;
    let length = 0;
    for (let col = 0; col < width; col++) {
      const cell = coast[row * width + col];
      if (cell === value) {
        length++;
      } else {
        runs.push(length);
        value = cell;
        length = 1;
      }
    }
    runs.push(length);
    rows.push(runs.map((n) => n.toString(36)).join('.'));
  }
  return rows;
}

export function renderMaskModule(rows) {
  const data = {
    source: `${SOURCE_PATH} (Natural Earth 1:50m admin-0), dilated by ${DILATE_CELLS} cell`,
    generator: 'scripts/generate-orbital-land-coast-mask.mjs',
    cellDeg: CELL_DEG,
    rows,
  };
  return `// Generated by scripts/generate-orbital-land-coast-mask.mjs from ${SOURCE_PATH}. Do not edit.\nexport default ${JSON.stringify(data)};\n`;
}

function main() {
  const topology = JSON.parse(readFileSync(resolve(ROOT, SOURCE_PATH), 'utf8'));
  const rendered = renderMaskModule(buildMask(topology));
  if (process.argv.includes('--check')) {
    const stale = MASK_PATHS.filter((path) => readFileSync(resolve(ROOT, path), 'utf8') !== rendered);
    if (stale.length) {
      console.error(`Stale land-coast mask: ${stale.join(', ')}. Run node scripts/generate-orbital-land-coast-mask.mjs`);
      process.exit(1);
    }
    return;
  }
  for (const path of MASK_PATHS) writeFileSync(resolve(ROOT, path), rendered);
  console.log(`Wrote ${MASK_PATHS.join(', ')} (${rendered.length} bytes each)`);
}

if (isMainModule(import.meta.url, process.argv[1])) main();
