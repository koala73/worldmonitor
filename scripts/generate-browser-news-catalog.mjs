#!/usr/bin/env node
// Writes the browser's slice of shared/news-catalog.json to
// src/config/news-catalog.browser.generated.ts. The browser bundle imports
// the slice so it ships only what the browser serves (no server-only fields,
// notes or server placements). It is a TS module rather than JSON because Vite
// inlines large JSON as an escaped JSON.parse string, which costs ~5 KB here.
// It also writes scripts/shared/news-digest-editions.json, the edition list
// the relay's classify loop iterates, so the relay image ships a few bytes
// instead of the whole catalog and does not redeploy on every feed edit, and
// scripts/shared/news-digest-warm-cells.json, the (edition, language) digests
// the relay's warm cycle requests, and shared/news-pool-layout.generated.ts,
// the editions, categories and languages ListNewsPool and the MCP news tools
// accept.
// Run under tsx: `node --import tsx <this>`.
// --check exits 1 when a committed output is stale.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { NEWS_CATALOG, buildDigestWarmCells, buildNewsPoolLayout, projectBrowserCatalog } from '../shared/news-catalog.ts';
import { getOutletProfile } from '../server/_shared/outlet-profile.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BROWSER_CATALOG_PATH = 'src/config/news-catalog.browser.generated.ts';
export const DIGEST_EDITIONS_PATH = 'scripts/shared/news-digest-editions.json';
export const DIGEST_WARM_CELLS_PATH = 'scripts/shared/news-digest-warm-cells.json';
export const NEWS_POOL_LAYOUT_PATH = 'shared/news-pool-layout.generated.ts';

export function renderDigestEditions() {
  return `${JSON.stringify(Object.keys(NEWS_CATALOG.layout.server), null, 2)}\n`;
}

export function renderDigestWarmCells() {
  return `${JSON.stringify(buildDigestWarmCells(), null, 2)}\n`;
}

export function renderNewsPoolLayout() {
  return [
    '// Generated by scripts/generate-browser-news-catalog.mjs from shared/news-catalog.json.',
    '// Do not edit; run `npm run generate`.',
    "import type { NewsPoolLayout } from './news-catalog';",
    '',
    `export const NEWS_POOL_LAYOUT: NewsPoolLayout = ${JSON.stringify(buildNewsPoolLayout((name) => getOutletProfile(name)?.language ?? 'en'), null, 2)};`,
    '',
  ].join('\n');
}

export function renderBrowserCatalog() {
  return [
    '// Generated by scripts/generate-browser-news-catalog.mjs from shared/news-catalog.json.',
    '// Do not edit; run `npm run generate`.',
    "import type { BrowserCatalog } from '../../shared/news-catalog-browser';",
    '',
    `export const BROWSER_NEWS_CATALOG: BrowserCatalog = ${JSON.stringify(projectBrowserCatalog(), null, 2)};`,
    '',
  ].join('\n');
}

function syncOutput(relPath, next, check) {
  const target = resolve(ROOT, relPath);
  let current = null;
  try {
    current = readFileSync(target, 'utf8');
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
  }
  if (current === next) return true;
  if (check) {
    console.error(`${relPath} is stale; run \`npm run generate\`.`);
    return false;
  }
  writeFileSync(target, next);
  return true;
}

function main() {
  const check = process.argv.includes('--check');
  const results = [
    syncOutput(BROWSER_CATALOG_PATH, renderBrowserCatalog(), check),
    syncOutput(DIGEST_EDITIONS_PATH, renderDigestEditions(), check),
    syncOutput(DIGEST_WARM_CELLS_PATH, renderDigestWarmCells(), check),
    syncOutput(NEWS_POOL_LAYOUT_PATH, renderNewsPoolLayout(), check),
  ];
  if (results.includes(false)) process.exit(1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
