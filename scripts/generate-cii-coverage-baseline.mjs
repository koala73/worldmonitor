#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync(new URL('../shared/cii-coverage-baseline.json', import.meta.url), 'utf8');
const baseline = JSON.parse(source);
const active = baseline.releases.at(-1);
if (baseline.schemaVersion !== 1 || !active?.scoredCountries?.length || !active?.families?.economicStress?.length) {
  throw new Error('Invalid CII coverage baseline');
}
const outputs = [
  ['../api/_cii-coverage-baseline.generated.js', `// Generated by scripts/generate-cii-coverage-baseline.mjs; do not edit.\nexport const CII_COVERAGE_BASELINE = ${JSON.stringify(active, null, 2)};\n`],
  ['./shared/cii-coverage-baseline.json', source],
];
for (const [relative, output] of outputs) {
  const path = new URL(relative, import.meta.url);
  if (process.argv.includes('--check')) {
    let current;
    try { current = readFileSync(path, 'utf8'); } catch { /* Missing output is stale. */ }
    if (current !== output) { console.error(`${relative} is stale; run npm run generate`); process.exitCode = 1; }
  } else writeFileSync(path, output);
}
