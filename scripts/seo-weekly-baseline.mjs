#!/usr/bin/env node

/**
 * Regenerate the AI-visibility baseline and scorecard from the weekly API
 * snapshots (#10024), so no one hand-supplies an export.
 *
 * Input, for one date: `gsc/<date>.json` (required), `bing/<date>.json` and
 * `umami/<date>.json` (each optional, absent when its credential is not
 * configured or its collection failed). Output: `baselines/<date>.json`,
 * through the existing `collectBaseline` contract, and `scorecards/<date>.md`,
 * compared against the newest earlier baseline.
 *
 * This script only assembles the source manifest. Each collector owns the
 * mapping from its own snapshot (`toScorecardSearchExport`,
 * `toScorecardBingSource`, `toScorecardReferralExport`), and
 * `seo-ai-visibility-collector.mjs` stays the only normalizer. A value is
 * mapped only where its meaning matches the contract field; everything else is
 * `null`, or a source marked partial or unavailable with the reason.
 *
 * The newest earlier baseline is also the template: its query-set contract,
 * referral classification, opportunity queue, guardrails and the declared
 * collection geography, locale, device and signed-in schedule carry forward,
 * so consecutive periods stay comparable. Its limitations do not carry
 * forward; this run states its own.
 *
 * Nothing is written unless both the baseline and the scorecard build, so a
 * failure leaves no half-updated pair behind.
 *
 * Usage:
 *   node scripts/seo-weekly-baseline.mjs --date 2026-11-03
 *
 * Options:
 *   --date <YYYY-MM-DD>           snapshot date (default today, UTC)
 *   --dir <path>                  measurement directory (default docs/research/seo-ai-visibility)
 *   --repository-revision <sha>   recorded revision (default `git rev-parse HEAD`)
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { isMainModule } from './lib/main-module.mjs';
import { toScorecardBingSource } from './seo-bing-collect.mjs';
import { collectBaseline } from './seo-ai-visibility-collector.mjs';
import {
  aiPlatformsForSchemaVersion,
  buildScorecard,
  compareScorecards,
  formatScorecardMarkdown,
} from './seo-ai-visibility-scorecard.mjs';
import { toScorecardSearchExport } from './seo-gsc-collect.mjs';
import { toScorecardReferralExport } from './seo-umami-collect.mjs';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_DIR = 'docs/research/seo-ai-visibility';
/** New cycles use the five-surface contract (see the directory README). */
const SCHEMA_VERSION = 2;
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;

export const AI_SURFACE_REASON = 'Not observed: the manual AI-answer panel was dropped on 2026-11-02 (#10024), and no automated observation replaces it. AI referral traffic is tracked in the Umami referral snapshot instead.';

export const RUN_LIMITATIONS = Object.freeze([
  'Generated by scripts/seo-weekly-baseline.mjs from the weekly API snapshots in gsc/, bing/ and umami/; no export was supplied by hand.',
  'No AI-answer observation was made: the manual panel was dropped on 2026-11-02 (#10024). The geography, locale, device and signed-in schedule are the declared panel context carried from the previous baseline so the periods stay comparable; the search and referral figures are site-wide and are not limited to that context.',
]);

function invariant(condition, message) {
  if (!condition) throw new Error(`[seo-weekly-baseline] ${message}`);
}

const missingBing = (date) => ({
  search: {
    status: 'unavailable',
    reason: `No Bing Webmaster snapshot for ${date}: BING_WEBMASTER_API_KEY is not configured or the Bing collection failed in that run.`,
  },
  aiPerformance: {
    status: 'unavailable',
    reason: `No Bing Webmaster snapshot for ${date}. Bing AI Performance has no Webmaster API method in any case.`,
  },
});

const missingUmami = (date) => ({
  status: 'unavailable',
  reason: `No Umami referral snapshot for ${date}: UMAMI_API_USERNAME and UMAMI_API_PASSWORD are not both configured, or the Umami collection failed in that run.`,
});

/**
 * The `sources` manifest `collectBaseline` reads, plus the observation time:
 * the latest snapshot's, so every window and the baseline itself end on or
 * before it.
 */
export function buildSourceManifest({ date, snapshots, querySet, template }) {
  invariant(DATE_PATTERN.test(date ?? ''), 'date must be YYYY-MM-DD');
  const { gsc, bing = null, umami = null } = snapshots;
  invariant(gsc, `the Search Console snapshot for ${date} is required`);
  const present = [['gsc', gsc], ['bing', bing], ['umami', umami]].filter(([, snapshot]) => snapshot);
  for (const [name, snapshot] of present) {
    invariant(
      snapshot.observedAt?.slice(0, 10) === date,
      `the ${name} snapshot was observed on ${snapshot.observedAt?.slice(0, 10)}, not ${date}`,
    );
  }
  const observedAt = present
    .map(([, snapshot]) => snapshot.observedAt)
    .reduce((latest, value) => (Date.parse(value) > Date.parse(latest) ? value : latest));
  const context = template.collectionContext;
  return {
    observedAt,
    sources: {
      schemaVersion: SCHEMA_VERSION,
      googleSearchConsole: toScorecardSearchExport(gsc, { querySet }),
      bingWebmaster: bing ? toScorecardBingSource(bing, { querySet }) : missingBing(date),
      referrals: umami
        ? toScorecardReferralExport(umami, { classification: template.referrals.classification })
        : missingUmami(date),
      collectionContext: {
        geography: context.geography,
        locale: context.locale,
        signedInStates: context.signedInStates,
        device: context.device,
        limitations: [...RUN_LIMITATIONS],
      },
      aiSurfaces: aiPlatformsForSchemaVersion(SCHEMA_VERSION).map((platform) => ({
        platform,
        status: 'unavailable',
        reason: AI_SURFACE_REASON,
      })),
      aiObservations: [],
    },
  };
}

/**
 * Search Console and Umami windows end on the run date, so they move every
 * week. Bing's end on the latest date Bing reports, which can stand still. The
 * scorecard refuses to compare a window with itself, so a Bing source that has
 * not moved past the previous baseline's is recorded as unavailable for the
 * week rather than failing the whole run.
 */
function withoutStalledBing(sources, previous) {
  const before = previous.search?.bingWebmaster;
  const current = sources.bingWebmaster.search;
  if (!before || before.status === 'unavailable' || current.status === 'unavailable') return sources;
  const previousWindow = before.windows.find((window) => window.label === '28d');
  const currentWindow = current.windows?.find((window) => window.label === '28d');
  if (!previousWindow || !currentWindow) return sources;
  if (currentWindow.startDate > previousWindow.startDate && currentWindow.endDate > previousWindow.endDate) {
    return sources;
  }
  return {
    ...sources,
    bingWebmaster: {
      ...sources.bingWebmaster,
      search: {
        status: 'unavailable',
        reason: `Bing data has not advanced since the ${previous.baselineId} baseline: its 28d window still ends on ${currentWindow.endDate}, so this week would repeat that period rather than measure a new one. The snapshot is kept in bing/.`,
      },
    },
  };
}

/**
 * The baseline for `date` and its scorecard markdown. `previous` is the newest
 * earlier baseline; it is both the template and the comparison period.
 */
export function buildWeeklyBaseline({ date, snapshots, querySet, previous, repositoryRevision }) {
  invariant(previous, 'an earlier baseline is required as the template');
  const manifest = buildSourceManifest({ date, snapshots, querySet, template: previous });
  const { observedAt } = manifest;
  const sources = withoutStalledBing(manifest.sources, previous);
  const baseline = collectBaseline({
    template: previous,
    querySet,
    sources,
    observedAt,
    repositoryRevision,
  });
  invariant(baseline.baselineId === date, `the baseline id ${baseline.baselineId} does not match ${date}`);
  const scorecard = buildScorecard(querySet, baseline);
  scorecard.comparison = compareScorecards(buildScorecard(querySet, previous), scorecard);
  return { baseline, markdown: formatScorecardMarkdown(scorecard) };
}

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const readOptional = (path) => (existsSync(path) ? readJson(path) : null);

/** The newest `baselines/<date>.json` strictly before `date`, so a rerun is idempotent. */
export function findPreviousBaseline(baselinesDir, date) {
  const earlier = readdirSync(baselinesDir)
    .filter((name) => /^\d{4}-\d{2}-\d{2}\.json$/.test(name) && name.slice(0, 10) < date)
    .sort();
  return earlier.length > 0 ? join(baselinesDir, earlier.at(-1)) : null;
}

export function parseArgs(argv) {
  const options = { date: null, dir: DEFAULT_DIR, repositoryRevision: undefined };
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index];
    const value = argv[index + 1];
    invariant(value !== undefined && !value.startsWith('--'), `${flag} requires a value`);
    index += 1;
    switch (flag) {
      case '--date': options.date = value; break;
      case '--dir': options.dir = value; break;
      case '--repository-revision': options.repositoryRevision = value; break;
      default: throw new Error(`[seo-weekly-baseline] unknown argument ${flag}`);
    }
  }
  invariant(options.date === null || DATE_PATTERN.test(options.date), '--date must be YYYY-MM-DD');
  return options;
}

export async function runCli(argv, { log = console.log, now = Date.now } = {}) {
  const options = parseArgs(argv);
  const date = options.date ?? new Date(now()).toISOString().slice(0, 10);
  const dir = resolve(REPO_ROOT, options.dir);
  const gscPath = join(dir, 'gsc', `${date}.json`);
  invariant(existsSync(gscPath), `no Search Console snapshot at ${gscPath}`);
  const previousPath = findPreviousBaseline(join(dir, 'baselines'), date);
  invariant(previousPath, `no baseline earlier than ${date} to use as the template`);
  const snapshots = {
    gsc: readJson(gscPath),
    bing: readOptional(join(dir, 'bing', `${date}.json`)),
    umami: readOptional(join(dir, 'umami', `${date}.json`)),
  };
  const { baseline, markdown } = buildWeeklyBaseline({
    date,
    snapshots,
    querySet: readJson(join(dir, 'query-set.json')),
    previous: readJson(previousPath),
    repositoryRevision: options.repositoryRevision,
  });
  const written = [join(dir, 'baselines', `${date}.json`), join(dir, 'scorecards', `${date}.md`)];
  mkdirSync(dirname(written[1]), { recursive: true });
  writeFileSync(written[0], `${JSON.stringify(baseline, null, 2)}\n`);
  writeFileSync(written[1], markdown);
  const sources = Object.entries(snapshots).map(([name, snapshot]) => `${name} ${snapshot ? 'present' : 'absent'}`);
  log(`[seo-weekly-baseline] ${sources.join(', ')}; compared with ${previousPath.replace(`${REPO_ROOT}/`, '')}`);
  log(`[seo-weekly-baseline] wrote ${written.map((path) => path.replace(`${REPO_ROOT}/`, '')).join(', ')}`);
  return { baseline, markdown, written };
}

if (isMainModule(import.meta.url, process.argv[1])) {
  runCli(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
