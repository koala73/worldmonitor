#!/usr/bin/env node
/**
 * Build-time docs page date manifest for the /docs JSON-LD rewrite.
 *
 * Mintlify serves docs HTML with no per-page dates, and routing middleware
 * cannot reach git history at request time — so the Article dateModified
 * injected by src/config/docs-locale-seo.ts comes from this committed map of
 * docs slug to the file's latest git commit date (YYYY-MM-DD).
 *
 * Slugs mirror Mintlify's path mapping: docs/architecture.mdx serves at
 * /docs/architecture and docs/zh/about.mdx at /docs/zh/about.
 *
 * Usage:
 *   npm run docs:dates          # regenerate src/config/docs-page-dates.generated.ts
 *   npm run docs:dates:check    # fail when the committed map is stale
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'src/config/docs-page-dates.generated.ts';
const CHECK = process.argv.includes('--check');

function listDocFiles() {
  const files = [];
  const walk = (dir) => {
    for (const entry of readdirSync(join(ROOT, dir), { withFileTypes: true })) {
      if (entry.isDirectory()) walk(`${dir}/${entry.name}`);
      else if (entry.name.endsWith('.mdx')) files.push(`${dir}/${entry.name}`);
    }
  };
  walk('docs');
  return files.sort();
}

function latestCommitDates() {
  const shallow = execFileSync('git', ['rev-parse', '--is-shallow-repository'], {
    cwd: ROOT, encoding: 'utf8',
  }).trim() === 'true';
  if (shallow) {
    throw new Error(
      'docs page dates need full git history (fetch-depth: 0); a shallow checkout resolves every file to HEAD',
    );
  }
  // One pass, newest-first: the first date seen per file is its latest commit.
  const output = execFileSync(
    'git',
    ['log', '--format=COMMIT:%cs', '--name-only', '--', 'docs/'],
    { cwd: ROOT, encoding: 'utf8' },
  );
  const dates = new Map();
  let current = null;
  for (const line of output.split('\n')) {
    const commit = line.match(/^COMMIT:(\d{4}-\d{2}-\d{2})$/);
    if (commit) {
      current = commit[1];
      continue;
    }
    const file = line.trim();
    if (file && current && !dates.has(file)) dates.set(file, current);
  }
  return dates;
}

function render(dates) {
  const entries = [...dates.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([slug, date]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(date)},`);
  return [
    '// Generated by scripts/generate-docs-page-dates.mjs. Do not edit.',
    'export const DOCS_PAGE_DATES: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

const files = listDocFiles();
const commitDates = latestCommitDates();
const missing = files.filter((file) => !commitDates.has(file));
if (missing.length > 0) {
  throw new Error(
    `docs page dates missing git history for: ${missing.join(', ')}`,
  );
}
const dates = new Map(
  files.map((file) => [file.replace(/^docs\//, '').replace(/\.mdx$/, ''), commitDates.get(file)]),
);
const expected = render(dates);
const outputPath = join(ROOT, OUTPUT);
const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : null;
if (actual === expected) {
  console.log(`docs page dates unchanged (${dates.size} pages)`);
} else if (CHECK) {
  throw new Error(`${OUTPUT} is stale — run npm run docs:dates`);
} else {
  writeFileSync(outputPath, expected);
  console.log(`docs page dates wrote ${dates.size} pages to ${OUTPUT}`);
}
